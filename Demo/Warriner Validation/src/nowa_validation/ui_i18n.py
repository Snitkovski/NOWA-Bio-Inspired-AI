def peek_lang(argv: list[str] | None = None) -> str:
    """Read ``--lang`` or ``NOWA_LANG`` without consuming argparse errors."""

    args = list(sys.argv[1:] if argv is None else argv)
    for index, item in enumerate(args):
        if item == "--lang" and index + 1 < len(args) and args[index + 1] in SUPPORTED:
            return args[index + 1]
        if item.startswith("--lang=") and item.split("=", 1)[1] in SUPPORTED:
            return item.split("=", 1)[1]
    env = os.environ.get("NOWA_LANG", "").strip().lower()
    if env in SUPPORTED:
        return env
    return DEFAULT_LANG


def t(key: str, lang: str | None = None, **kwargs: object) -> str:
    chosen = lang if lang in SUPPORTED else peek_lang()
    table = STRINGS.get(chosen) or STRINGS[DEFAULT_LANG]
    text = table.get(key) or STRINGS[DEFAULT_LANG].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def assert_catalog_parity() -> None:
    en = set(STRINGS["en"])
    ru = set(STRINGS["ru"])
    if en != ru:
        raise AssertionError(f"missing ru={sorted(en - ru)} missing en={sorted(ru - en)}")
    empty = [key for key in en if not STRINGS["en"][key] or not STRINGS["ru"][key]]
    if empty:
        raise AssertionError(f"empty warriner strings: {empty}")
